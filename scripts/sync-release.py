#!/usr/bin/env python3
"""Keep every provider configuration on the latest published Flow Steward release.

    python3 scripts/sync-release.py                    # pin the latest release
    python3 scripts/sync-release.py --version 0.9.19   # pin one release
    python3 scripts/sync-release.py --check            # verify, change nothing

The release's own registry-verification asset supplies the Compact and
PostgreSQL index digests; the RabbitMQ digest is the one that release's Compose
file uses. Every digest is resolved anonymously before anything is written, so
a pin a user cannot pull is never committed. `release.env` is the one record of
the pinned release; all other files only repeat its image references.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RELEASE_FILE = ROOT / "release.env"
APP_REPOSITORY = "Flow-Steward/flow-steward-app"
GHCR_NAMESPACE = "ghcr.io/flow-steward"
RABBITMQ_SOURCE = "infra/docker/docker-compose.compact.yaml"
DIGEST = r"sha256:[0-9a-f]{64}"
VERSION_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")

# Key in release.env -> (image name as written in configurations, pin pattern).
IMAGES = {
    "COMPACT_IMAGE": f"{GHCR_NAMESPACE}/flow-steward-compact",
    "POSTGRES_IMAGE": f"{GHCR_NAMESPACE}/flow-steward-postgres",
    "RABBITMQ_IMAGE": "rabbitmq",
}
TEXT_SUFFIXES = {".md", ".yml", ".yaml", ".toml", ".sh", ".env", ".json", ".txt"}
# A hand-written release number anywhere else is how pins went stale before.
HAND_WRITTEN_VERSION = re.compile(r"(?<![\w.])v?\d+\.\d+\.\d+(?![\w.])")
VERSION_SCAN_EXEMPT = ("release.env", ".github/", "tests/", "scripts/")

HEADER = """\
# Generated by scripts/sync-release.py from a published Flow Steward release.
# Do not edit by hand: the sync-release workflow rewrites this file and every
# image pin in this repository when a new release is published.
"""


def pin_pattern(image: str) -> re.Pattern[str]:
    # `rabbitmq@` must not match the tail of another image path.
    return re.compile(rf"(?<![\w./-]){re.escape(image)}@{DIGEST}")


def http_get(url: str, *, accept: str | None = None, token: str | None = None) -> bytes:
    headers = {"User-Agent": "flow-steward-deploy-sync"}
    if accept:
        headers["Accept"] = accept
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=30) as response:  # noqa: S310 - fixed https hosts
        return response.read()


def github_json(path: str) -> dict:
    token = os.environ.get("GITHUB_TOKEN") or None
    body = http_get(
        f"https://api.github.com/repos/{APP_REPOSITORY}/{path}",
        accept="application/vnd.github+json",
        token=token,
    )
    return json.loads(body)


def release_metadata(version: str | None) -> tuple[str, dict]:
    release = github_json(f"releases/tags/v{version}" if version else "releases/latest")
    if release.get("draft") or release.get("prerelease"):
        raise SystemExit(f"{release.get('tag_name')} is not a published stable release")
    tag = str(release.get("tag_name", ""))
    resolved = tag.removeprefix("v")
    if not VERSION_PATTERN.match(resolved):
        raise SystemExit(f"Unexpected release tag: {tag!r}")
    return resolved, release


def release_images(version: str, release: dict) -> dict[str, str]:
    assets = [
        asset
        for asset in release.get("assets", [])
        if re.fullmatch(r"registry-verification-[\w.-]+\.json", asset.get("name", ""))
    ]
    if len(assets) != 1:
        raise SystemExit(f"v{version} must carry exactly one registry-verification asset")
    verification = json.loads(http_get(assets[0]["browser_download_url"]))
    if str(verification.get("version")) != version:
        raise SystemExit(f"Registry verification describes {verification.get('version')}, not {version}")
    if verification.get("failures"):
        raise SystemExit(f"v{version} registry verification reported failures")
    digests: dict[str, str] = {}
    for registry in verification.get("registries") or []:
        for image in registry.get("images") or []:
            reference = str(image.get("reference", ""))
            name, _, tag = reference.rpartition(":")
            digest = str(image.get("index_digest", ""))
            if tag == version and re.fullmatch(DIGEST, digest):
                digests[name] = digest
    pins = {}
    for key in ("COMPACT_IMAGE", "POSTGRES_IMAGE"):
        name = IMAGES[key]
        if name not in digests:
            raise SystemExit(f"v{version} registry verification has no {name}:{version}")
        pins[key] = f"{name}@{digests[name]}"
    compose = http_get(
        f"https://raw.githubusercontent.com/{APP_REPOSITORY}/v{version}/{RABBITMQ_SOURCE}"
    ).decode()
    rabbitmq = set(re.findall(rf"rabbitmq:[\w.-]+@({DIGEST})", compose))
    if len(rabbitmq) != 1:
        raise SystemExit(f"v{version} {RABBITMQ_SOURCE} must name exactly one RabbitMQ digest")
    pins["RABBITMQ_IMAGE"] = f"rabbitmq@{rabbitmq.pop()}"
    return pins


def registry_endpoint(image: str) -> tuple[str, str, str]:
    """Return (token URL, manifest base URL, repository) for an anonymous pull."""
    if image.startswith("ghcr.io/"):
        repository = image.removeprefix("ghcr.io/")
        return (
            f"https://ghcr.io/token?scope=repository:{repository}:pull",
            f"https://ghcr.io/v2/{repository}",
            repository,
        )
    repository = image if "/" in image else f"library/{image}"
    return (
        f"https://auth.docker.io/token?service=registry.docker.io&scope=repository:{repository}:pull",
        f"https://registry-1.docker.io/v2/{repository}",
        repository,
    )


def assert_pullable(reference: str) -> None:
    image, _, digest = reference.partition("@")
    token_url, base, _ = registry_endpoint(image)
    token = json.loads(http_get(token_url)).get("token")
    accept = ", ".join(
        (
            "application/vnd.oci.image.index.v1+json",
            "application/vnd.docker.distribution.manifest.list.v2+json",
            "application/vnd.oci.image.manifest.v1+json",
            "application/vnd.docker.distribution.manifest.v2+json",
        )
    )
    try:
        http_get(f"{base}/manifests/{digest}", accept=accept, token=token)
    except urllib.error.HTTPError as error:
        raise SystemExit(f"{reference} is not anonymously pullable (HTTP {error.code})") from error


def read_release() -> dict[str, str]:
    values = {}
    for line in RELEASE_FILE.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            key, _, value = line.partition("=")
            values[key] = value
    missing = {"FLOW_STEWARD_RELEASE", *IMAGES} - values.keys()
    if missing:
        raise SystemExit(f"release.env lacks {', '.join(sorted(missing))}")
    return values


def render_release(version: str, pins: dict[str, str]) -> str:
    lines = [f"FLOW_STEWARD_RELEASE={version}", *(f"{key}={pins[key]}" for key in IMAGES)]
    return HEADER + "\n".join(lines) + "\n"


def tracked_text_files() -> list[Path]:
    output = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    files = []
    for name in output.splitlines():
        path = ROOT / name
        if path.suffix in TEXT_SUFFIXES and path.is_file() and path != RELEASE_FILE:
            files.append(path)
    return files


def rewrite(text: str, pins: dict[str, str]) -> str:
    for key, image in IMAGES.items():
        text = pin_pattern(image).sub(pins[key], text)
    return text


def problems(files: list[Path], pins: dict[str, str]) -> list[str]:
    found = []
    for path in files:
        relative = path.relative_to(ROOT).as_posix()
        text = path.read_text(encoding="utf-8")
        for key, image in IMAGES.items():
            for match in pin_pattern(image).finditer(text):
                if match.group(0) != pins[key]:
                    found.append(f"{relative}: {match.group(0)} differs from release.env {key}")
        # A bare tag (`flow-steward-compact:0.9.19`, `:latest`) bypasses the pin.
        for image in IMAGES.values():
            for match in re.finditer(rf"(?<![\w./-]){re.escape(image)}:[\w.-]+", text):
                found.append(f"{relative}: {match.group(0)} is a tag; use the release.env digest")
        if not relative.startswith(VERSION_SCAN_EXEMPT):
            for match in HAND_WRITTEN_VERSION.finditer(text):
                found.append(f"{relative}: hand-written release number {match.group(0)}")
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", help="release to pin (X.Y.Z); default: latest")
    parser.add_argument("--check", action="store_true", help="verify consistency only")
    args = parser.parse_args()
    if args.version and not VERSION_PATTERN.match(args.version.removeprefix("v")):
        parser.error("--version must look like 0.9.19")
    files = tracked_text_files()

    if args.check:
        pins = read_release()
        issues = problems(files, pins)
        for issue in issues:
            print(issue, file=sys.stderr)
        if issues:
            return 1
        print(f"All provider configurations use release.env ({pins['FLOW_STEWARD_RELEASE']}).")
        return 0

    version, release = release_metadata(args.version.removeprefix("v") if args.version else None)
    pins = release_images(version, release)
    for reference in pins.values():
        assert_pullable(reference)
    RELEASE_FILE.write_text(render_release(version, pins), encoding="utf-8")
    changed = []
    for path in files:
        text = path.read_text(encoding="utf-8")
        updated = rewrite(text, pins)
        if updated != text:
            path.write_text(updated, encoding="utf-8")
            changed.append(path.relative_to(ROOT).as_posix())
    print(f"Pinned Flow Steward {version}.")
    for name in changed:
        print(f"  updated {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
